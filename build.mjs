import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/** Emit the deployment's lazy browser module without introducing runtime imports. */
async function main() {
  const root = new URL('./', import.meta.url)
  const modules = ['syntax.js', 'rpc.js', 'integration.js', 'review.js', 'client-entry.js']
  const chunks = []
  for (const name of modules) {
    let text = await readFile(new URL(name, root), 'utf8')
    text = text.replace(/^import .*\r?\n/gmu, '').replace(/^export /gmu, '')
    chunks.push(`// ${name}\n${text}`)
  }
  const en = JSON.parse(await readFile(new URL('locale/en.json', root), 'utf8'))
  const zh = JSON.parse(await readFile(new URL('locale/zh.json', root), 'utf8'))
  const text = `// Generated by build.mjs; edit client-entry.js and its local modules.\nwindow.__ModuleLoader__.load({ id: 'dsh-workspace-reference', factory(require) {\nconst React = require('react');\nconst { Modal, ReferenceChip } = require('@deepseek-ai/dsh-client-ui-primitives');\nconst en = ${JSON.stringify(en)};\nconst zh = ${JSON.stringify(zh)};\n${chunks.join('\n')}\nreturn { inject, apply };\n} });\n`
  const target = new URL('client.js', root)
  await writeFile(target, text, 'utf8')
  console.log(`Built ${fileURLToPath(target)}`)
}
main().catch(error => { console.error(error); process.exitCode = 1 })
